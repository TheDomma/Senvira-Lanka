import { catalogueEntries, projectLatLngToSvg } from '../destinations';
import { VERIFIED_DESTINATION_COORDINATES } from '../destinationCoordinates';
import { getExperienceById } from '../experiences';
import type { CostItem, PriceRange, StopRef } from './types';

/** Small builders that keep the itinerary data readable. */
export const dest = (id: string, label?: string): StopRef => ({ kind: 'destination', id, label });
export const exp = (id: string, label?: string): StopRef => ({ kind: 'experience', id, label });

export const inc = (label: string, note?: string): CostItem => ({ label, status: 'included', note });
export const opt = (label: string, note?: string): CostItem => ({ label, status: 'optional', note });
export const fee = (label: string, note?: string): CostItem => ({ label, status: 'excluded', note });

export const range = (min: number, max: number, open = false): PriceRange => ({ min, max, open });

const destinationById = new Map(catalogueEntries.map((entry) => [entry.id, entry]));

export interface ResolvedStop {
  kind: 'destination' | 'experience';
  id: string;
  label: string;
  href: string;
  /** Extra context shown next to the label (theme for experiences, region for destinations). */
  context: string;
}

/**
 * Resolves a stop to a real, current route. Throws at build time if the destination or
 * experience no longer exists, so package pages can never link to a dead page.
 *
 * Destinations: the site has no per-destination route yet; the directory page resolves
 * `/destinations/#<id>` to the selected place, which is what experience pages already use.
 * Experiences: `/experiences/<themeId>/<id>/` is generated by src/pages/experiences/[theme]/[id].astro.
 */
export function resolveStop(stop: StopRef): ResolvedStop {
  if (stop.kind === 'destination') {
    const entry = destinationById.get(stop.id);
    if (!entry) {
      throw new Error(`[packages] Destination "${stop.id}" does not exist in the destinations catalogue.`);
    }
    return {
      kind: 'destination',
      id: stop.id,
      label: stop.label ?? entry.name,
      href: `/destinations/#${stop.id}`,
      context: entry.regionCluster ?? 'Destination',
    };
  }
  const experience = getExperienceById(stop.id);
  if (!experience) {
    throw new Error(`[packages] Experience "${stop.id}" does not exist in the experiences data.`);
  }
  return {
    kind: 'experience',
    id: stop.id,
    label: stop.label ?? experience.primaryDestinationName,
    href: `/experiences/${experience.themeId}/${experience.id}/`,
    context: experience.themeLabel,
  };
}

export interface MapPoint {
  id: string;
  name: string;
  x: number;
  y: number;
}

/** Projects a verified coordinate id onto the 100×110 island sketch. */
export function resolveMapPoint(id: string): MapPoint {
  const record = VERIFIED_DESTINATION_COORDINATES[id];
  if (!record) {
    throw new Error(`[packages] No verified coordinates for map stop "${id}".`);
  }
  const { svgX, svgY } = projectLatLngToSvg(record.lat, record.lng);
  const entry = destinationById.get(id);
  return { id, name: entry?.name ?? id, x: svgX, y: svgY };
}
